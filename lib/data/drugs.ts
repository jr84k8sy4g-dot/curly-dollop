export function findDrug(id: string): Drug | undefined {
  return DRUGS.find((d) => d.id === id);
}

export function searchDrugs(query: string, category?: string): Drug[] {
  const q = query.trim().toLowerCase();
  return DRUGS.filter((d) => {
    const matchesCategory = !category || d.category === category;
    if (!matchesCategory) return false;
    if (!q) return true;
    return (
      d.name.toLowerCase().includes(q) ||
      d.genericName.toLowerCase().includes(q) ||
      d.category.toLowerCase().includes(q) ||
      d.brandNames.some((b) => b.toLowerCase().includes(q))
    );
  });
}

export const DRUG_CATEGORIES = Array.from(
  new Set(DRUGS.map((d) => d.category)),
).sort();
